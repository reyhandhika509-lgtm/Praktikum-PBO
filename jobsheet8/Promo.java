package jobsheet8;

public class Promo {

    private String kode;
    private int persen;

    public Promo(String kode, int persen) {
        this.kode = kode;
        this.persen = persen;
    }

    public String getKode() {
        return kode;
    }

    public int getPersen() {
        return persen;
    }
}
    

